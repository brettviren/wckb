"""Policy: the LLM-facing guidance of a store, as named, versioned elements.

A policy element is an instructions snippet (assembled into CLAUDE.md), a
skill (SKILL.md), a hook (Claude Code settings) or settings.  Elements come
from three sources, searched in order: this store's ``policy`` items, the
stores it reaches (up and peer), and the builtins shipped with kb.  So a
group can publish policy as items, members adopt it by name, and anyone can
fork a builtin by revising it locally.

The store's settings hold the selection (``policy.use``), the enactment
``policy.target`` and the ``autonomy`` the human grants.  ``kb policy enact``
resolves the selection, writes the files, and records what it wrote in
``policy.lock.json`` so that drift (someone edited CLAUDE.md by hand, a newer
version was released) is visible in ``kb policy status``.
"""

