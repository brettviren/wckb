# -- policy elements and their sources ---------------------------------------

@dataclass
class Element:
    name: str
    version: int
    type: str
    stage: str
    source: str                 # "builtin", "here", or a neighbor label
    content: str
    title: str = ""
    summary: str = ""
    order: int = 50
    applies_to: list = field(default_factory=list)
    item: Item | None = None
    based_on: str | None = None

    @property
    def spec(self) -> str:
        return f"{self.name}@{self.version}"

    @property
    def digest(self) -> str:
        return hashlib.sha256(self.content.encode()).hexdigest()

    @property
    def origin(self) -> str:
        where = "builtin" if self.source == "builtin" else f"{self.source}:{self.item.id}"
        return f"{where}"


def _data(rel: str) -> str:
    return (resources.files("kb") / "data" / rel).read_text()


def builtins() -> list[Element]:
    out = []
    for e in json.loads(_data("policies.json")):
        out.append(Element(e["name"], e["version"], e["type"], "released", "builtin", _data(e["file"]),
                           e.get("title", e["name"]), e.get("description", ""), e.get("order", 50),
                           e.get("applies_to", [])))
    return out


def _content_of(kb: Store, rec: Item) -> str:
    for r in rec.renditions:
        if r["role"] == "content":
            t = rec.text(r["name"])
            if t is None:
                p = content.resolve(kb, rec, r, fetch_urls=False)
                t = p.read_text() if p is not None else None
            if t is not None:
                return t
    return ""


def from_store(kb: Store, label: str) -> list[Element]:
    out = []
    for rec in kb.items.values():
        if rec.kind != "policy":
            continue
        d = rec.data
        out.append(Element(d["name"], d["version"], d["policy_type"], d["stage"], label,
                           _content_of(kb, rec), d.get("title", ""), d.get("summary", ""),
                           d.get("order", 50), d.get("applies_to", []), rec, d.get("based_on")))
    return out


def available(kb: Store, reach: int = 2) -> list[Element]:
    """Every policy element visible from *kb*: here, then reachable stores, then builtins."""
    from .federation import reachable
    out = from_store(kb, "here")
    for r in reachable(kb, reach):
        out += from_store(r.kb, r.label)
    return out + builtins()


def parse_spec(spec: str) -> tuple[str, str | None]:
    name, _, ver = spec.partition("@")
    return name, (ver or None)


def resolve(kb: Store, spec: str, elements: list[Element] | None = None) -> Element:
    """name -> latest released version from the nearest source that has the name;
    name@N -> exactly version N; name@draft -> this store's draft."""
    name, ver = parse_spec(spec)
    elements = elements if elements is not None else available(kb)
    named = [e for e in elements if e.name == name]
    if not named:
        raise KBError(f"no policy named {name!r}; see kb policy list")
    if ver == "draft":
        drafts = [e for e in named if e.stage == "draft" and e.source == "here"]
        if not drafts:
            raise KBError(f"no draft of {name} in this store")
        return max(drafts, key=lambda e: e.version)
    if ver is not None:
        try:
            n = int(ver)
        except ValueError:
            raise KBError(f"bad policy version in {spec!r}: use NAME, NAME@N or NAME@draft") from None
        exact = [e for e in named if e.version == n and e.stage != "draft"]
        if not exact:
            raise KBError(f"no released version {n} of {name}")
        return exact[0]
    first_source = named[0].source
    released = [e for e in named if e.source == first_source and e.stage != "draft"]
    if not released:
        released = [e for e in named if e.stage != "draft"]
    if not released:
        raise KBError(f"{name} has only drafts; use {name}@draft or release it")
    return max(released, key=lambda e: e.version)


# -- policy.toml: selection, target, autonomy ---------------------------------

def settings(kb: Store) -> dict:
    """Policy selection and target ("policy") and autonomy ("autonomy"), from the store's settings."""
    return {"policy": kb.setting("policy", {}), "autonomy": kb.setting("autonomy", {})}


def save_settings(kb: Store, data: dict) -> None:
    for key in ("policy", "autonomy"):
        if key in data:
            kb.set_setting(key, data[key])


def default_settings(scope: str, target: str = ".") -> dict:
    return {"policy": {"use": list(DEFAULT_USE.get(scope, DEFAULT_USE["other"])), "target": target},
            "autonomy": json.loads(json.dumps(DEFAULT_AUTONOMY.get(scope, DEFAULT_AUTONOMY["other"])))}


def _guard(kb: Store, approved: str | None, what: str) -> None:
    if not kb.cfg.is_agent:
        return
    level = kb.cfg.autonomy_for("policy")
    if level == "never":
        raise KBError(f"autonomy: {what} is reserved for the human")
    if level == "ask" and not approved:
        raise KBError(f"autonomy: {what} needs the human's approval; ask, then pass --approved \"<their words>\"")


def use(kb: Store, specs: list[str], approved: str | None = None) -> list[str]:
    _guard(kb, approved, "changing the policy selection")
    elements = available(kb)
    for s in specs:
        resolve(kb, s, elements)
    data = settings(kb)
    sel = data.setdefault("policy", {}).setdefault("use", [])
    for s in specs:
        name = parse_spec(s)[0]
        sel[:] = [x for x in sel if parse_spec(x)[0] != name] + [s]
    save_settings(kb, data)
    return sel


def drop(kb: Store, names: list[str], approved: str | None = None) -> list[str]:
    _guard(kb, approved, "changing the policy selection")
    data = settings(kb)
    sel = data.setdefault("policy", {}).setdefault("use", [])
    missing = [n for n in names if n not in [parse_spec(x)[0] for x in sel]]
    if missing:
        raise KBError(f"not selected: {', '.join(missing)}")
    sel[:] = [x for x in sel if parse_spec(x)[0] not in names]
    save_settings(kb, data)
    return sel


def set_autonomy(kb: Store, assignments: list[str]) -> dict:
    """key=level or push.NEIGHBOR=level; only a person may change autonomy."""
    if kb.cfg.is_agent:
        raise KBError("autonomy is granted by the human; an agent cannot change it")
    data = settings(kb)
    a = data.setdefault("autonomy", {})
    for item in assignments:
        key, _, level = item.partition("=")
        if level not in AUTONOMY_LEVELS:
            raise KBError(f"{item!r}: level must be one of {', '.join(AUTONOMY_LEVELS)}")
        if "." in key:
            action, target = key.split(".", 1)
            cur = a.get(action)
            if not isinstance(cur, dict):
                a[action] = {"default": cur or "ask"}
            a[action][target] = level
        else:
            if isinstance(a.get(key), dict):
                a[key]["default"] = level
            else:
                a[key] = level
    save_settings(kb, data)
    return a


# -- authoring policy items ---------------------------------------------------

def _local_versions(kb: Store, name: str) -> list[Item]:
    return sorted((r for r in kb.items.values() if r.kind == "policy" and r.data["name"] == name),
                  key=lambda r: r.data["version"])


def new(kb: Store, name: str, ptype: str, text: str, title: str | None = None, summary: str | None = None,
        order: int | None = None, applies_to=(), based_on: str | None = None, version: int = 1,
        supersedes: str | None = None) -> Item:
    if ptype not in TYPES:
        raise KBError(f"policy type must be one of {', '.join(TYPES)}")
    if ptype == "hook":
        _parse_hook(text, name)
    if any(r.data["stage"] == "draft" for r in _local_versions(kb, name)):
        raise KBError(f"{name} already has a draft here; kb policy edit it, or release it first")
    fields = {"title": title or f"Policy {name}", "summary": summary or f"{ptype} policy {name}, version {version}.",
              "name": name, "version": version, "policy_type": ptype, "stage": "draft",
              "subject": ["kb/policy"]}
    if order is not None:
        fields["order"] = order
    if applies_to:
        fields["applies_to"] = list(applies_to)
    if based_on:
        fields["based_on"] = based_on
    if supersedes:
        fields["supersedes"] = [supersedes]
    return authoring.new(kb, "policy", fields, text=text, content_file=("content", FILENAME[ptype]))


def _draft(kb: Store, name: str) -> Item:
    drafts = [r for r in _local_versions(kb, name) if r.data["stage"] == "draft"]
    if not drafts:
        raise KBError(f"no draft of {name} in this store; kb policy revise {name} makes one")
    return drafts[-1]


def edit(kb: Store, name: str, text: str) -> Item:
    from .edit import set_content
    rec = _draft(kb, name)
    if rec.data["policy_type"] == "hook":
        _parse_hook(text, name)
    return set_content(kb, rec.id, text, "content")


def _stage(kb: Store, rec: Item, stage: str, approved: str | None) -> Item:
    import copy
    data = copy.deepcopy(rec.data)
    data["stage"] = stage
    return kb.save(Item(data, kb), "stage", {"stage": stage}, approved=approved)


def release(kb: Store, name: str, approved: str | None = None) -> Item:
    _guard(kb, approved, "releasing a policy version")
    return _stage(kb, _draft(kb, name), "released", approved)


def deprecate(kb: Store, name: str, approved: str | None = None) -> Item:
    _guard(kb, approved, "deprecating a policy")
    vs = [r for r in _local_versions(kb, name) if r.data["stage"] == "released"]
    if not vs:
        raise KBError(f"no released version of {name} in this store")
    return _stage(kb, vs[-1], "deprecated", approved)


def revise(kb: Store, name: str, text: str | None = None) -> Item:
    """A new draft version: the next version of a local policy, or a local fork
    of a builtin or neighbor's policy (which then takes precedence here)."""
    base = resolve(kb, name)
    local = _local_versions(kb, name)
    version = max([base.version] + [r.data["version"] for r in local]) + 1
    supersedes = None
    based_on = None
    if base.source == "here":
        supersedes = base.item.id
        based_on = base.based_on
    else:
        based_on = f"{base.source}:{base.spec}"
    return new(kb, name, base.type, text if text is not None else base.content,
               base.title, base.summary, base.order, base.applies_to, based_on, version, supersedes)


# -- enactment -------------------------------------------------------------------

def target_dir(kb: Store, target: str | None = None) -> Path:
    t = target or settings(kb).get("policy", {}).get("target", ".")
    if t == "user":
        return Path(os.environ.get("CLAUDE_CONFIG_DIR", Path.home() / ".claude"))
    p = Path(t).expanduser()
    return (p if p.is_absolute() else kb.root / p).resolve()


def _claude_md(tdir: Path, user: bool) -> Path:
    return tdir / "CLAUDE.md"   # project root, or ~/.claude for the user target


def _settings_path(tdir: Path, user: bool) -> Path:
    return tdir / "settings.json" if user else tdir / ".claude" / "settings.json"


def _skills_dir(tdir: Path, user: bool) -> Path:
    return tdir / "skills" if user else tdir / ".claude" / "skills"


def _parse_hook(text: str, name: str) -> dict:
    try:
        h = json.loads(text)
    except json.JSONDecodeError as exc:
        raise KBError(f"hook policy {name}: not JSON: {exc}") from None
    if not isinstance(h, dict) or "event" not in h or "command" not in h:
        raise KBError(f"hook policy {name}: needs at least event and command")
    if not h["command"].startswith(HOOK_PREFIXES):
        raise KBError(f"hook policy {name}: command must start with one of {HOOK_PREFIXES} so kb can manage it")
    return h


def store_context(kb: Store, tdir: Path) -> str:
    """The generated, always-present first section: where the store is, its neighbors, autonomy."""
    from .federation import neighbors
    try:
        rel = os.path.relpath(kb.root, tdir)
    except ValueError:
        rel = str(kb.root)
    where = "this directory" if rel == "." else f"`{rel}`"
    lines = ["## This knowledge base", "",
             f"- Store **{kb.cfg.name}**: a {kb.cfg.scope} store (access: {kb.cfg.access}) in {where}. "
             + ("`kb` finds it from here." if rel in (".", "kb") else f"Run kb as `kb -C {kb.root}`."),
             ]
    nbs = neighbors(kb)
    if nbs:
        lines.append("- Neighbors: " + "; ".join(
            f"**{n.name}** ({n.relation}{', writable' if n.writable else ', read-only' if n.available else ', not available here'})"
            for n in nbs) + ". Read them with `--reach 1` (or `--in NAME`) on ls/search/context.")
    else:
        lines.append("- No neighbor stores are configured.")
    lines += ["", "Autonomy the human has granted you here:", "", "| action | level | meaning |", "|---|---|---|"]
    a = kb.cfg.autonomy
    for key in ("capture", "review", "curate", "policy", "pull", "accept", "merge"):
        if key in a and isinstance(a[key], str):
            lines.append(f"| {key} | {kb.cfg.autonomy_for(key)} | {AUTONOMY_MEANING.get(key, '')} |")
    push = a.get("push", "ask")
    push = push if isinstance(push, dict) else {"default": push}
    for t in [n.name for n in nbs] or ["default"]:
        lines.append(f"| push to {t} | {kb.cfg.autonomy_for('push', t)} | {AUTONOMY_MEANING['push']} |")
    lines += ["", "never: leave it to the human. ask: ask first, and pass their words with --approved. "
              "auto: go ahead, then tell the human what you did."]
    return "\n".join(lines)


def plan(kb: Store, target: str | None = None) -> dict:
    """What enact would write: {path: content} plus the resolved elements."""
    sel = settings(kb).get("policy", {}).get("use", [])
    elements = available(kb)
    chosen = [resolve(kb, s, elements) for s in sel]
    tdir = target_dir(kb, target)
    user = (target or settings(kb).get("policy", {}).get("target")) == "user"
    files: dict[Path, str] = {}

    instr = sorted((e for e in chosen if e.type == "instructions"), key=lambda e: (e.order, e.name))
    block = [BEGIN, store_context(kb, tdir)]
    for e in instr:
        block += ["", MARK.format(e.spec), e.content.strip()]
    block.append(END)
    block_text = "\n".join(block) + "\n"
    cmd = _claude_md(tdir, user)
    files[cmd] = _splice(cmd.read_text() if cmd.exists() else "", block_text)

    for e in chosen:
        if e.type == "skill":
            files[_skills_dir(tdir, user) / e.name / "SKILL.md"] = e.content

    sp = _settings_path(tdir, user)
    conf = json.loads(sp.read_text()) if sp.exists() else {}
    hooks = conf.setdefault("hooks", {})
    for event in list(hooks):
        hooks[event] = [h for h in hooks[event]
                        if not any(x.get("command", "").startswith(HOOK_PREFIXES) for x in h.get("hooks", []))]
        if not hooks[event]:
            del hooks[event]
    for e in chosen:
        if e.type == "hook":
            h = _parse_hook(e.content, e.name)
            entry = {"hooks": [{"type": "command", "command": h["command"]}]}
            if h.get("timeout"):
                entry["hooks"][0]["timeout"] = h["timeout"]
            if h.get("matcher"):
                entry = {"matcher": h["matcher"]} | entry
            hooks.setdefault(h["event"], []).append(entry)
    if not hooks:
        conf.pop("hooks")
    files[sp] = json.dumps(conf, indent=2) + "\n"
    return {"target": tdir, "user": user, "elements": chosen, "files": files, "block": block_text}


def _splice(text: str, block: str) -> str:
    if BEGIN in text and END in text:
        head, rest = text.split(BEGIN, 1)
        _, tail = rest.split(END, 1)
        return head + block.rstrip("\n") + tail
    sep = "" if not text or text.endswith("\n\n") else ("\n" if text.endswith("\n") else "\n\n")
    return text + sep + block


def _sha(text: str) -> str:
    return hashlib.sha256(text.encode()).hexdigest()


def enact(kb: Store, target: str | None = None, dry_run: bool = False) -> dict:
    p = plan(kb, target)
    changes = []
    for path, text in p["files"].items():
        old = path.read_text() if path.exists() else None
        if old != text:
            changes.append({"path": str(path), "action": "create" if old is None else "update",
                            "diff": "".join(difflib.unified_diff(
                                (old or "").splitlines(True), text.splitlines(True),
                                str(path), str(path), n=1))})
    lock_skills = {}
    old_lock = read_lock(kb)
    if not dry_run:
        # Remove skills we enacted before and no longer select.
        keep = {e.name for e in p["elements"] if e.type == "skill"}
        for name, info in old_lock.get("skills", {}).items():
            if name not in keep:
                f = Path(info["path"])
                if f.exists() and _sha(f.read_text()) == info["sha256"]:
                    f.unlink()
                    if not any(f.parent.iterdir()):
                        f.parent.rmdir()
                    changes.append({"path": str(f), "action": "remove", "diff": ""})
        for path, text in p["files"].items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
        for e in p["elements"]:
            if e.type == "skill":
                f = _skills_dir(p["target"], p["user"]) / e.name / "SKILL.md"
                lock_skills[e.name] = {"path": str(f), "sha256": _sha(e.content)}
        lock = {
            "enacted_at": now(), "by": kb.cfg.user, "target": str(p["target"]),
            "policies": [{"name": e.name, "version": e.version, "type": e.type, "stage": e.stage,
                          "source": e.origin, "digest": e.digest} for e in p["elements"]],
            "block_sha256": _sha(p["block"]),
            "claude_md": str(_claude_md(p["target"], p["user"])),
            "skills": lock_skills,
        }
        kb.set_setting(LOCK, lock)
        log.info("enacted policy of %s in %s: %d files changed", kb.cfg.name, p["target"], len(changes))
    return {"target": str(p["target"]), "policies": [e.spec + ("" if e.source == "here" else f" ({e.source})")
                                                      for e in p["elements"]],
            "changes": changes, "dry_run": dry_run}


def read_lock(kb: Store) -> dict:
    return kb.setting(LOCK, {}) or {}


def _enacted_block(lock: dict) -> str | None:
    p = Path(lock.get("claude_md", ""))
    if not p.exists():
        return None
    text = p.read_text()
    if BEGIN not in text or END not in text:
        return None
    return BEGIN + text.split(BEGIN, 1)[1].split(END, 1)[0] + END + "\n"


def _snippet(block: str, spec: str) -> str | None:
    m = MARK.format(spec)
    if m not in block:
        return None
    after = block.split(m, 1)[1]
    for stop in ("<!-- kb:policy ", END):
        after = after.split(stop, 1)[0] if stop in after else after
    return after.strip() + "\n"


def status(kb: Store) -> list[dict]:
    """What needs attention: not enacted, newer versions, local edits of enacted files."""
    out = []
    lock = read_lock(kb)
    sel = settings(kb).get("policy", {}).get("use", [])
    elements = available(kb)
    locked = {p["name"]: p for p in lock.get("policies", [])}
    if not lock:
        out.append({"what": "never enacted", "fix": "kb policy enact"})
    for s in sel:
        name, ver = parse_spec(s)
        try:
            e = resolve(kb, s, elements)
        except KBError as exc:
            out.append({"policy": s, "what": str(exc), "fix": f"kb policy drop {name}"})
            continue
        lk = locked.get(name)
        if lk is None:
            out.append({"policy": s, "what": "selected but not enacted", "fix": "kb policy enact"})
        elif lk["digest"] != e.digest:
            out.append({"policy": s, "what": f"enacted {name}@{lk['version']}, resolves now to {e.spec}",
                        "fix": "kb policy enact"})
        if ver is not None and ver != "draft":
            newer = [x for x in elements if x.name == name and x.stage == "released" and x.version > e.version]
            if newer:
                out.append({"policy": s, "what": f"pinned; {name}@{max(x.version for x in newer)} is available",
                            "fix": f"kb policy use {name}"})
        if e.stage == "deprecated":
            out.append({"policy": s, "what": "deprecated", "fix": "choose a replacement"})
    for name in locked:
        if name not in [parse_spec(s)[0] for s in sel]:
            out.append({"policy": name, "what": "enacted but no longer selected", "fix": "kb policy enact"})
    if lock:
        block = _enacted_block(lock)
        if block is None:
            out.append({"what": f"policy block missing from {lock.get('claude_md')}", "fix": "kb policy enact"})
        elif _sha(block) != lock["block_sha256"]:
            for p in lock["policies"]:
                if p["type"] != "instructions":
                    continue
                e = next((x for x in elements if x.name == p["name"] and x.version == p["version"]), None)
                snip = _snippet(block, f"{p['name']}@{p['version']}")
                if e is not None and snip is not None and snip.strip() != e.content.strip():
                    out.append({"policy": p["name"], "what": "edited in CLAUDE.md since enacted",
                                "fix": f"kb policy capture {p['name']} (keep the edit) or kb policy enact (discard)"})
        for name, info in lock.get("skills", {}).items():
            f = Path(info["path"])
            if not f.exists():
                out.append({"policy": name, "what": "skill file removed", "fix": "kb policy enact"})
            elif _sha(f.read_text()) != info["sha256"]:
                out.append({"policy": name, "what": f"{f} edited since enacted",
                            "fix": f"kb policy capture {name} (keep the edit) or kb policy enact (discard)"})
    return out


def enacted_content(kb: Store, name: str) -> str:
    lock = read_lock(kb)
    p = next((x for x in lock.get("policies", []) if x["name"] == name), None)
    if p is None:
        raise KBError(f"{name} is not enacted")
    if p["type"] == "instructions":
        block = _enacted_block(lock)
        snip = _snippet(block or "", f"{name}@{p['version']}")
        if snip is None:
            raise KBError(f"cannot find {name} in {lock.get('claude_md')}")
        return snip
    if p["type"] == "skill":
        return Path(lock["skills"][name]["path"]).read_text()
    raise KBError(f"{p['type']} policies are captured by editing their item: kb policy revise {name}")


def capture(kb: Store, name: str) -> Item:
    """Turn edits made to an enacted file into a draft policy version in this store."""
    text = enacted_content(kb, name)
    current = resolve(kb, name)
    if text.strip() == current.content.strip():
        raise KBError(f"{name}: the enacted text matches {current.spec}; nothing to capture")
    drafts = [r for r in _local_versions(kb, name) if r.data["stage"] == "draft"]
    if drafts:
        return edit(kb, name, text)
    return revise(kb, name, text)


def diff(kb: Store, name: str, against: str | None = None) -> str:
    """Enacted text vs its source, or (with *against*) two versions."""
    e = resolve(kb, name)
    if against:
        o = resolve(kb, f"{parse_spec(name)[0]}@{against}")
        a, b, la, lb = o.content, e.content, o.spec, e.spec
    else:
        a, b, la, lb = e.content, enacted_content(kb, parse_spec(name)[0]), e.spec, "enacted"
    return "".join(difflib.unified_diff(a.splitlines(True), b.splitlines(True), la, lb))
